// One "pad" slot per connected Bluetooth controller (up to MAX_PADS).
// Shared between the Bluetooth side (bt_bridge.c) and the USB side (usb_device.c, main.c).
//
// Locking: everything here is touched either from Bluepad32 callbacks (async_context) or from the
// main loop while it holds the async_context lock - except where noted.
#pragma once
#include <stdbool.h>
#include <stdint.h>

#include "config.h"
#include "xinput_report.h"

// Controllers whose Bluetooth reports have the USB layout, so they can be passed through as-is
typedef enum { NAT_NONE, NAT_DS4, NAT_DS5, NAT_SWITCH } native_kind_t;

typedef struct {
    uint8_t len;
    uint8_t data[64];
} pkt_t;

#define RING_SIZE 16
typedef struct {
    pkt_t p[RING_SIZE];
    uint8_t head, tail;
} ring_t;

void ring_clear(ring_t* r);
void ring_push(ring_t* r, const uint8_t* data, uint8_t len);   // drops the oldest when full
bool ring_pop(ring_t* r, pkt_t* out);

typedef struct {
    bool used;              // a controller is connected and ready in this slot
    bool fetching;          // still reading its feature reports (not usable yet)
    native_kind_t kind;     // NAT_NONE = can only be shown as Xbox 360
    uint16_t pid;           // real product id (DS4 v1/v2, DualSense / Edge)
    uint8_t mac[6];         // Bluetooth address, display order (MSB first)

    // Raw feature reports from the controller (report id first)
    pkt_t feat_calib;       // DS4 / DS5: 0x05
    pkt_t feat_pairing;     // DS5: 0x09
    pkt_t feat_firmware;    // DS4: 0xA3, DS5: 0x20

    // Xbox 360 view
    xinput_report_t xi;
    bool xi_dirty;
    bool rumble_pending;    // set from tud_task (main loop, no lock) - main loop only
    uint8_t rumble_strong, rumble_weak;

    // Native view
    ring_t to_usb;          // BT input reports converted to USB layout (id first, 64 bytes)
    ring_t to_bt;           // USB output reports waiting for the controller (main loop only)
    ring_t local;           // replies generated by the Pico itself (Switch 0x81, main loop only)
} pad_t;

extern pad_t pads[MAX_PADS];
